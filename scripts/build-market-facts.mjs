#!/usr/bin/env node
/**
 * build-market-facts.mjs — compile test-data/market-facts/<as_of>/ into
 * src/data/market-facts.ts (PLAN-HELLOG-0007, market_facts_contract 1).
 *
 *   node scripts/build-market-facts.mjs                 write src/data/market-facts.ts
 *   node scripts/build-market-facts.mjs --check         fail if the file drifted
 *   node scripts/build-market-facts.mjs --update-sums   rewrite SHA256SUMS first
 *   --root <dir>  market-facts root (default test-data/market-facts)
 *   --out <file>  output file (default src/data/market-facts.ts)
 *
 * Input: the lexicographically latest <as_of> directory holding gates.json;
 * every other *.json in it is one market file (<cc>.json). Each market is
 * compiled independently, so adding a market never changes another market's
 * generated bytes. The output embeds a sha256 of the canonical data that
 * src/lib/market-publication.ts re-checks at start-up.
 *
 * Every fact is written to the artifact, gated or not: "absent" is a property
 * of the SERVED response (the publication predicate), never of this data.
 */
import { createHash } from "node:crypto";
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import Ajv from "ajv";

const here = dirname(fileURLToPath(import.meta.url));
const repo = join(here, "..");

export function canonicalJson(v) {
  if (v === null || typeof v !== "object") return JSON.stringify(v);
  if (Array.isArray(v)) return `[${v.map(canonicalJson).join(",")}]`;
  return `{${Object.keys(v).sort().map((k) => `${JSON.stringify(k)}:${canonicalJson(v[k])}`).join(",")}}`;
}
const sha256 = (buf) => createHash("sha256").update(buf).digest("hex");

function fail(msg) {
  throw new Error(`build-market-facts: ${msg}`);
}

export function build({ root, schemaPath, policyPath }) {
  const schema = JSON.parse(readFileSync(schemaPath, "utf8"));
  const policy = JSON.parse(readFileSync(policyPath, "utf8"));
  const ajv = new Ajv({ allErrors: true, strict: false });
  ajv.addSchema(schema);
  const validator = (def) => {
    const v = ajv.getSchema(`market-facts.schema.json#/$defs/${def}`);
    if (!v) fail(`schema definition ${def} missing`);
    return v;
  };
  const check = (def, value, label) => {
    const v = validator(def);
    if (!v(value)) fail(`${label} failed schema validation: ${ajv.errorsText(v.errors)}`);
  };
  check("policy", policy, "scripts/market-facts.policy.json");

  const asOfDirs = readdirSync(root, { withFileTypes: true })
    .filter((d) => d.isDirectory() && existsSync(join(root, d.name, "gates.json")))
    .map((d) => d.name)
    .sort();
  if (!asOfDirs.length) fail(`no <as_of>/gates.json under ${root}`);
  const asOf = asOfDirs.at(-1);
  const dir = join(root, asOf);

  // SHA256SUMS: every listed file must match its recorded hash.
  const sumsPath = join(dir, "SHA256SUMS");
  const files = readdirSync(dir).filter((f) => f.endsWith(".json")).sort();
  if (!existsSync(sumsPath)) fail(`${sumsPath} missing (run with --update-sums)`);
  const sums = new Map(
    readFileSync(sumsPath, "utf8").split("\n").filter(Boolean).map((l) => {
      const [h, name] = l.split(/\s+/);
      return [name, h];
    }),
  );
  for (const f of files) {
    const actual = sha256(readFileSync(join(dir, f)));
    if (sums.get(f) !== actual) fail(`SHA256SUMS mismatch for ${f} (recorded ${sums.get(f) ?? "none"}, actual ${actual})`);
  }
  for (const name of sums.keys()) if (!files.includes(name)) fail(`SHA256SUMS lists ${name}, which does not exist`);

  const gatesFile = JSON.parse(readFileSync(join(dir, "gates.json"), "utf8"));
  check("gatesFile", gatesFile, "gates.json");
  const gateKeys = new Set();
  for (const g of gatesFile.gates) {
    if (gateKeys.has(g.gate_id)) fail(`duplicate gate ${g.gate_id}`);
    gateKeys.add(g.gate_id);
  }

  const banned = policy.banned_prose_patterns.map((p) => new RegExp(p, "i"));
  const markets = {};
  for (const f of files.filter((n) => n !== "gates.json")) {
    const raw = readFileSync(join(dir, f));
    const data = JSON.parse(raw.toString("utf8"));
    check("marketFile", data, f);
    if (`${data.market}.json` !== f) fail(`${f}: market "${data.market}" does not match the file name`);
    if (data.as_of !== asOf) fail(`${f}: as_of ${data.as_of} is not the directory ${asOf}`);
    if (data.release_evidence_version !== gatesFile.release_evidence_version)
      fail(`${f}: release_evidence_version ${data.release_evidence_version} != gates.json ${gatesFile.release_evidence_version}`);

    const ids = new Set();
    const keyOf = (id, market) => (policy.global_gates.includes(id) ? id : `${id}:${market}`);
    const requireGates = (kind, own, market, label) => {
      for (const m of policy.mandatory_gates_by_kind[kind] ?? [])
        if (!own.includes(m)) fail(`${label}: kind "${kind}" must list mandatory gate "${m}"`);
      for (const id of own) if (!gateKeys.has(keyOf(id, market))) fail(`${label}: unknown gate "${id}" (no ${keyOf(id, market)} in gates.json)`);
    };
    for (const fact of data.facts) {
      if (ids.has(fact.fact_id)) fail(`${f}: duplicate fact_id ${fact.fact_id}`);
      ids.add(fact.fact_id);
      if (fact.market !== data.market) fail(`${fact.fact_id}: market mismatch`);
      if (fact.release_evidence_version !== data.release_evidence_version) fail(`${fact.fact_id}: release_evidence_version mismatch`);
      if (fact.status === "roadmap") {
        if (fact.is_capability) fail(`${fact.fact_id}: roadmap fact must have is_capability false`);
        if (!fact.statement.startsWith("Planned, not available:")) fail(`${fact.fact_id}: roadmap statement must start "Planned, not available:"`);
      } else if (!fact.is_capability) fail(`${fact.fact_id}: capability fact must have is_capability true`);
      requireGates(fact.kind, fact.publish_gates, data.market, fact.fact_id);
      for (const re of banned) if (re.test(fact.statement)) fail(`${fact.fact_id}: statement matches banned phrase ${re}`);
    }
    requireGates("price", data.price.publish_gates, data.market, `${f} price`);
    for (const [label, text] of [["price.pending_note", data.price.pending_note]])
      for (const re of banned) if (re.test(text)) fail(`${f} ${label} matches banned phrase ${re}`);
    for (const t of data.withheld) if (!policy.withheld_topics.includes(t)) fail(`${f}: unknown withheld topic "${t}"`);
    for (const gt of gatesFile.gates.filter((g) => g.market === data.market || g.market === "global"))
      for (const re of banned) if (gt.public_price_qualifier && re.test(gt.public_price_qualifier)) fail(`gate ${gt.gate_id}: qualifier matches banned phrase ${re}`);
    markets[data.market] = { source: { file: `test-data/market-facts/${asOf}/${f}`, sha256: sha256(raw) }, data };
  }
  if (!Object.keys(markets).length) fail("no market files");

  const sorted = Object.fromEntries(Object.keys(markets).sort().map((k) => [k, markets[k]]));
  const payload = {
    market_facts_contract: 1,
    release_evidence_version: gatesFile.release_evidence_version,
    as_of: asOf,
    policy,
    gates: [...gatesFile.gates].sort((a, b) => a.gate_id.localeCompare(b.gate_id)),
    markets: sorted,
  };
  const digest = sha256(canonicalJson(payload));
  const ts = `/* eslint-disable */
// GENERATED by scripts/build-market-facts.mjs from test-data/market-facts/${asOf}/ — do not edit.
// Run \`npm run build:market-facts\` to regenerate; \`npm run check:market-facts\` fails on drift.
// A hand edit changes the digest below and the server then publishes nothing.
import type { MarketFactsData } from "../lib/market-publication.js";

export const MARKET_FACTS_DATA: MarketFactsData = ${JSON.stringify(payload, null, 2)};

export const MARKET_FACTS_SHA256 = "${digest}";
`;
  return { ts, dir, files, digest };
}

function main() {
  const args = process.argv.slice(2);
  const opt = (name, dflt) => {
    const i = args.indexOf(name);
    return i >= 0 ? resolve(args[i + 1]) : dflt;
  };
  const root = opt("--root", join(repo, "test-data/market-facts"));
  const out = opt("--out", join(repo, "src/data/market-facts.ts"));
  try {
    if (args.includes("--update-sums")) {
      const dirs = readdirSync(root, { withFileTypes: true }).filter((d) => d.isDirectory() && existsSync(join(root, d.name, "gates.json")));
      for (const d of dirs) {
        const dir = join(root, d.name);
        const lines = readdirSync(dir).filter((f) => f.endsWith(".json")).sort().map((f) => `${sha256(readFileSync(join(dir, f)))}  ${f}`);
        writeFileSync(join(dir, "SHA256SUMS"), `${lines.join("\n")}\n`);
      }
    }
    const { ts, digest } = build({
      root,
      schemaPath: join(here, "market-facts.schema.json"),
      policyPath: join(here, "market-facts.policy.json"),
    });
    if (args.includes("--check")) {
      const current = existsSync(out) ? readFileSync(out, "utf8") : "";
      if (current !== ts) {
        console.error(`build-market-facts: ${out} is out of date with test-data/market-facts. Run: npm run build:market-facts`);
        process.exit(1);
      }
      console.log(`build-market-facts: OK (drift check passed, sha256 ${digest.slice(0, 12)}…)`);
      return;
    }
    writeFileSync(out, ts);
    console.log(`build-market-facts: wrote ${out} (sha256 ${digest.slice(0, 12)}…)`);
  } catch (err) {
    console.error(err.message);
    process.exit(1);
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
