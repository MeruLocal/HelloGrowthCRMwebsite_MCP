#!/usr/bin/env node
// ============================================================================
// sync-website-mirror.mjs — rebuild the bundled integrations mirror from the
// website source, and move the SYNCED_AT stamps that prove it was done.
//
//   node scripts/sync-website-mirror.mjs                 rewrite the mirror
//   node scripts/sync-website-mirror.mjs --check         report drift, write nothing
//   node scripts/sync-website-mirror.mjs --check --strict  ...and fail if the
//                                                        website repo is absent
//   node scripts/sync-website-mirror.mjs --website=../hellocrmwebsite
//
// WHY THIS EXISTS
// src/tools/integrations.ts was hand-copied from the website on 2026-06-17 and
// then left alone. By 2026-09-08 it was 83 days stale and publishing a count
// (630) the website had retired in August, inside — among other places — the
// plan feature bullets that pricing_get_plans hands to buyers. Nothing caught
// it, because a hand-copied mirror has no mechanism that can.
//
// src/lib/content-freshness.ts made the staleness VISIBLE (/health degrades,
// audit-live-mcp FAILs). This script is the other half: the thing that makes
// the staleness FIXABLE in one command, so the alarm has an off switch that
// isn't "edit the number".
//
// HOW IT READS THE WEBSITE
// It evaluates the website's TypeScript rather than parsing it, the same
// technique hellocrmwebsite/scripts/check-integration-count.mjs uses: node
// strips the types on its own, so the only thing missing is `@/` alias
// resolution, which is rewritten to absolute file URLs in a temp copy. That
// matters because the catalog is a MERGE of three sources through
// mergeCatalogs() + isValidIntegrationEntry(), and route slugs go through
// getIntegrationPath()'s alias table. A regex over the source would mirror the
// text; evaluating it mirrors what the website actually serves.
//
// THE MAPPING, stated once so it can be checked:
//   slug        ← entry.slug
//   name        ← entry.name
//   category    ← the containing category's slug
//   description ← entry.whatItDoes, VERBATIM
//   status      ← entry.status when set (absent means live — see integrations.ts)
//   route       ← getIntegrationPath(entry.slug), so alias slugs resolve to the
//                 canonical page rather than a URL that 301s
//
// Two defects in the hand-copied mirror were found by running this against it:
// `ga4-measurement` had its description truncated mid-sentence at "(e.g." by
// an old shorten-to-one-sentence heuristic, and `hunter-io` pointed at
// /integrations/hunter-io where the alias table says /integrations/hunter.
// Both are fixed simply by regenerating; neither was findable by eye across
// 630 rows. That is the argument for this script in one sentence.
//
// Exit codes: 0 = in sync, written, or skipped; 1 = drift found in --check;
// 2 = the website repo could not be read (only fatal when writing, or with
// --strict).
// ============================================================================

import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const REPO = path.resolve(HERE, "..");

const args = process.argv.slice(2);
const CHECK = args.includes("--check");
const STRICT = args.includes("--strict");
const websiteArg = args.find((a) => a.startsWith("--website="))?.slice("--website=".length);

// Default to a sibling checkout, which is how both repos sit on the dev
// machine. Override with --website= or WEBSITE_REPO in CI.
const WEBSITE = path.resolve(websiteArg ?? process.env.WEBSITE_REPO ?? path.join(REPO, "..", "hellocrmwebsite"));

const MIRROR = path.join(REPO, "src/tools/integrations.ts");
const FRESHNESS = path.join(REPO, "src/lib/content-freshness.ts");

const BEGIN = "// >>> GENERATED BY scripts/sync-website-mirror.mjs — do not hand-edit below <<<";
const END = "// >>> END GENERATED <<<";

const today = new Date().toISOString().slice(0, 10);

function die(code, msg) {
  console.error(msg);
  process.exit(code);
}

if (!fs.existsSync(path.join(WEBSITE, "src/lib/integrations-catalog-data.ts"))) {
  const where =
    `Cannot find the website repo at ${WEBSITE}.\n` +
    `Pass --website=<path> or set WEBSITE_REPO. This script reads:\n` +
    `  src/lib/integrations-catalog-data.ts\n  src/lib/integration-routes.ts`;

  // `npm run verify` calls this in --check mode, and most people running it do
  // not have the website checked out beside this repo. Failing there would
  // teach everyone to skip verify, which costs more than the check is worth —
  // so a missing website is a SKIP, loudly, and only --strict makes it fatal.
  // CI that DOES check out both repos should pass --strict, otherwise a broken
  // checkout would silently turn the drift gate off.
  if (CHECK && !STRICT) {
    console.log(`⏭  skipping mirror drift check — ${where.split("\n")[0]}`);
    console.log("   (pass --strict to make this fatal, e.g. in CI where both repos are checked out)");
    process.exit(0);
  }
  die(2, where);
}

/**
 * Import a website module by rewriting its `@/lib/...` specifiers to absolute
 * file URLs in a temp copy outside both repos. Node ≥22.18 strips the types.
 */
async function loadWebsiteModule(rel) {
  const origDir = path.dirname(path.join(WEBSITE, rel));
  const src = fs
    .readFileSync(path.join(WEBSITE, rel), "utf8")
    // `@/lib/X` → the website's src/lib/X.ts as an absolute file URL.
    .replace(
      /from "@\/lib\/([^"]+)"/g,
      (_m, mod) => `from ${JSON.stringify(pathToFileURL(path.join(WEBSITE, "src/lib", `${mod}.ts`)).href)}`,
    )
    // Relative specifiers (`./x`, `../../scripts/data/y.json`) resolve against
    // the ORIGINAL file's directory, not this relocated temp copy. JSON imports
    // also need an explicit import attribute under Node's ESM loader. The
    // website added one such import (integration-junk-slugs) on 2026-09-22,
    // which this script could not read until it learned to rewrite relative
    // paths too — the integrations mirror silently stopped syncing until then.
    .replace(/from "(\.\.?\/[^"]+)"/g, (_m, spec) => {
      const abs = path.resolve(origDir, spec);
      if (spec.endsWith(".json")) {
        return `from ${JSON.stringify(pathToFileURL(abs).href)} with { type: "json" }`;
      }
      const file = abs.endsWith(".ts") ? abs : `${abs}.ts`;
      return `from ${JSON.stringify(pathToFileURL(file).href)}`;
    });
  const tmp = path.join(os.tmpdir(), `hgcrm-mirror-${path.basename(rel)}-${process.pid}.ts`);
  fs.writeFileSync(tmp, src, "utf8");
  try {
    return await import(pathToFileURL(tmp).href);
  } finally {
    try { fs.unlinkSync(tmp); } catch { /* best effort */ }
  }
}

const { INTEGRATIONS_CATALOG, INTEGRATIONS_CATALOG_SUMMARY } = await loadWebsiteModule(
  "src/lib/integrations-catalog-data.ts",
);
const { getIntegrationPath } = await loadWebsiteModule("src/lib/integration-routes.ts");

// ── build the two generated blocks ──────────────────────────────────────────

const q = (v) => JSON.stringify(v);

const categoryLines = INTEGRATIONS_CATALOG.map(
  (c) => `  { slug: ${q(c.slug)}, title: ${q(c.title)}, shortLabel: ${q(c.shortLabel)} },`,
);

const rowLines = [];
let rowCount = 0;
for (const category of INTEGRATIONS_CATALOG) {
  rowLines.push(`  // ── ${category.title} (${category.integrations.length}) ──`);
  for (const entry of category.integrations) {
    rowCount++;
    const status = entry.status ? `, status: ${q(entry.status)}` : "";
    rowLines.push(
      `  { slug: ${q(entry.slug)}, name: ${q(entry.name)}, category: ${q(category.slug)}, ` +
        `description: ${q(entry.whatItDoes)}${status}, route: ${q(getIntegrationPath(entry.slug))} },`,
    );
  }
  rowLines.push("");
}
while (rowLines.at(-1) === "") rowLines.pop();

const categoriesBlock = [
  BEGIN,
  "const INTEGRATION_CATEGORIES: IntegrationCategory[] = [",
  ...categoryLines,
  "];",
  END,
].join("\n");

const rowsBlock = [
  BEGIN,
  "const INTEGRATIONS: IntegrationRecord[] = [",
  ...rowLines,
  "];",
  END,
].join("\n");

// ── splice them in ──────────────────────────────────────────────────────────

let mirror = fs.readFileSync(MIRROR, "utf8");
const before = mirror;

function replaceBlock(source, marker, block, label) {
  const start = source.indexOf(`${BEGIN}\n${marker}`);
  if (start === -1) {
    die(2, `Could not find the generated ${label} block in src/tools/integrations.ts.\nExpected the marker line:\n  ${BEGIN}\nimmediately followed by:\n  ${marker}`);
  }
  const stop = source.indexOf(END, start);
  if (stop === -1) die(2, `Unterminated generated ${label} block — no ${END} after it.`);
  return source.slice(0, start) + block + source.slice(stop + END.length);
}

mirror = replaceBlock(mirror, "const INTEGRATION_CATEGORIES", categoriesBlock, "categories");
mirror = replaceBlock(mirror, "const INTEGRATIONS", rowsBlock, "rows");

// The stamp is part of the sync, not a separate chore: a regenerated mirror
// that still claims June is worse than an honestly old one.
mirror = mirror.replace(/const SYNCED_AT = "\d{4}-\d{2}-\d{2}";/, `const SYNCED_AT = ${q(today)};`);
mirror = mirror.replace(
  /Source: hellocrmwebsite\/src\/lib\/integrations-catalog-data\.ts — SYNCED_AT \d{4}-\d{2}-\d{2}/,
  `Source: hellocrmwebsite/src/lib/integrations-catalog-data.ts — SYNCED_AT ${today}`,
);
mirror = mirror.replace(
  /Source: hellocrmwebsite\/src\/lib\/integration-routes\.ts — SYNCED_AT \d{4}-\d{2}-\d{2}/,
  `Source: hellocrmwebsite/src/lib/integration-routes.ts — SYNCED_AT ${today}`,
);
mirror = mirror.replace(
  /\/\/ INTEGRATIONS_CATALOG, \d+ rows: \d+ live \+ \d+ scaffolded\) — SYNCED_AT \d{4}-\d{2}-\d{2}/,
  `// INTEGRATIONS_CATALOG, ${INTEGRATIONS_CATALOG_SUMMARY.total} rows: ${INTEGRATIONS_CATALOG_SUMMARY.liveCount} live + ${INTEGRATIONS_CATALOG_SUMMARY.scaffoldedCount} scaffolded) — SYNCED_AT ${today}`,
);

let freshness = fs.readFileSync(FRESHNESS, "utf8");
const freshnessBefore = freshness;
freshness = freshness.replace(/(\n  integrations: )"\d{4}-\d{2}-\d{2}"/, `$1${q(today)}`);

// ── report ──────────────────────────────────────────────────────────────────

const rowsChanged = before !== mirror;
const stampChanged = freshnessBefore !== freshness;

console.log(`website:  ${WEBSITE}`);
console.log(
  `catalog:  ${INTEGRATIONS_CATALOG_SUMMARY.total} rows · ` +
    `${INTEGRATIONS_CATALOG_SUMMARY.liveCount} live · ` +
    `${INTEGRATIONS_CATALOG_SUMMARY.scaffoldedCount} scaffolded · ` +
    `${INTEGRATIONS_CATALOG.length} categories`,
);
console.log(`emitted:  ${rowCount} rows, ${categoryLines.length} categories`);

if (rowCount !== INTEGRATIONS_CATALOG_SUMMARY.total) {
  die(2, `Emitted ${rowCount} rows but the website's own summary says ${INTEGRATIONS_CATALOG_SUMMARY.total}. Refusing to write a mirror that disagrees with its source.`);
}

if (CHECK) {
  if (!rowsChanged && !stampChanged) {
    console.log("\n✅ in sync — the bundled mirror matches the website source.");
    process.exit(0);
  }
  console.error(
    "\n❌ DRIFT: the bundled mirror no longer matches the website source." +
      (rowsChanged ? "\n   · src/tools/integrations.ts rows or stamp are out of date" : "") +
      (stampChanged ? "\n   · src/lib/content-freshness.ts integrations stamp is out of date" : "") +
      "\n\nRun: node scripts/sync-website-mirror.mjs",
  );
  process.exit(1);
}

if (!rowsChanged && !stampChanged) {
  console.log("\n✅ already in sync — nothing written.");
  process.exit(0);
}

fs.writeFileSync(MIRROR, mirror, "utf8");
fs.writeFileSync(FRESHNESS, freshness, "utf8");
console.log(`\n✅ rewrote the mirror and stamped it ${today}.`);
console.log("   Next: npx tsc --noEmit && npm test — the mirror is code, not data.");
