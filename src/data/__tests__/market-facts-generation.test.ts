import { cpSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { afterEach, describe, expect, it } from "vitest";
// @ts-expect-error plain ESM script, no types
import { build, canonicalJson } from "../../../scripts/build-market-facts.mjs";
import { MARKET_FACTS_DATA, MARKET_FACTS_SHA256 } from "../market-facts.js";
import { canonicalJson as libCanonical } from "../../lib/market-publication.js";

const repo = join(dirname(fileURLToPath(import.meta.url)), "../../..");
const schemaPath = join(repo, "scripts/market-facts.schema.json");
const policyPath = join(repo, "scripts/market-facts.policy.json");
const AS_OF = "2026-11-02";
const tmps: string[] = [];

function scratch() {
  const root = mkdtempSync(join(tmpdir(), "mf-"));
  tmps.push(root);
  cpSync(join(repo, "test-data/market-facts", AS_OF), join(root, AS_OF), { recursive: true });
  return { root, dir: join(root, AS_OF) };
}
const run = (root: string) => build({ root, schemaPath, policyPath }) as { ts: string; digest: string };

import { createHash } from "node:crypto";
function resum(dir: string) {
  const lines = ["gates.json", "uk.json", "zz.json"]
    .filter((f) => { try { readFileSync(join(dir, f)); return true; } catch { return false; } })
    .map((f) => `${createHash("sha256").update(readFileSync(join(dir, f))).digest("hex")}  ${f}`);
  writeFileSync(join(dir, "SHA256SUMS"), `${lines.join("\n")}\n`);
}
function editUk(dir: string, fn: (uk: any) => void) {
  const p = join(dir, "uk.json");
  const uk = JSON.parse(readFileSync(p, "utf8"));
  fn(uk);
  writeFileSync(p, JSON.stringify(uk, null, 2));
  resum(dir);
}

afterEach(() => { for (const t of tmps.splice(0)) rmSync(t, { recursive: true, force: true }); });

describe("generated artifact", () => {
  it("is exactly what the generator produces from the committed data (no drift)", () => {
    expect(readFileSync(join(repo, "src/data/market-facts.ts"), "utf8")).toBe(run(join(repo, "test-data/market-facts")).ts);
  });

  it("is deterministic: two runs are byte-identical", () => {
    const { root } = scratch();
    expect(run(root).ts).toBe(run(root).ts);
  });

  it("the generator's and the runtime's canonical JSON agree", () => {
    const sample = { b: [1, { z: 1, a: null }], a: "x" };
    expect(canonicalJson(sample)).toBe(libCanonical(sample));
    expect(run(join(repo, "test-data/market-facts")).digest).toBe(MARKET_FACTS_SHA256);
  });

  it("keeps gated facts in the artifact (absence is a served-response property)", () => {
    const ids = MARKET_FACTS_DATA.markets.uk!.data.facts.map((f) => f.fact_id);
    expect(ids).toEqual(expect.arrayContaining(["uk.price.monthly", "uk.price.annual", "uk.security.soc2"]));
    expect(MARKET_FACTS_DATA.gates.every((g) => g.status === "unmet")).toBe(true);
  });

  it("the roadmap facts are exactly the GoCardless item, with is_capability false", () => {
    const roadmap = MARKET_FACTS_DATA.markets.uk!.data.facts.filter((f) => f.status === "roadmap");
    expect(roadmap.map((f) => f.fact_id)).toEqual(["uk.pay.gocardless"]);
    expect(roadmap[0]!.is_capability).toBe(false);
    expect(roadmap[0]!.statement.startsWith("Planned, not available:")).toBe(true);
  });

  it("every fact and the price carry source, verified_on and truth_version", () => {
    const uk = MARKET_FACTS_DATA.markets.uk!.data;
    for (const f of uk.facts) {
      expect(f.source).toBeTruthy();
      expect(f.verified_on).toMatch(/^\d{4}-\d{2}-\d{2}$/);
      expect(f.truth_version).toBeTruthy();
    }
    expect(uk.price).toMatchObject({ billing_currency: "USD", truth_version: expect.any(String), verified_on: expect.any(String), source: expect.any(String) });
  });

  it("adding a market leaves every other market's generated bytes unchanged", () => {
    const { root, dir } = scratch();
    const before = JSON.stringify(MARKET_FACTS_DATA.markets.uk);
    const uk = JSON.parse(readFileSync(join(dir, "uk.json"), "utf8"));
    const zz = JSON.parse(JSON.stringify(uk).replaceAll('"uk.', '"zz.').replaceAll('"market": "uk"', '"market": "zz"').replaceAll('"scope_ref": "market:uk"', '"scope_ref": "market:zz"'));
    zz.market = "zz";
    for (const f of zz.facts) f.market = "zz";
    writeFileSync(join(dir, "zz.json"), JSON.stringify(zz, null, 2));
    const gates = JSON.parse(readFileSync(join(dir, "gates.json"), "utf8"));
    gates.gates.push(
      { ...gates.gates.find((g: any) => g.gate_id === "stripe-flow1:uk"), gate_id: "stripe-flow1:zz", market: "zz" },
      { ...gates.gates.find((g: any) => g.gate_id === "website-deploy:uk"), gate_id: "website-deploy:zz", market: "zz" },
    );
    writeFileSync(join(dir, "gates.json"), JSON.stringify(gates, null, 2));
    const sums = ["gates.json", "uk.json", "zz.json"].map((f) => `${createHash("sha256").update(readFileSync(join(dir, f))).digest("hex")}  ${f}`);
    writeFileSync(join(dir, "SHA256SUMS"), `${sums.join("\n")}\n`);
    const out = run(root).ts;
    expect(out).toContain('"zz"');
    const ukBlock = JSON.stringify(JSON.parse(out.slice(out.indexOf("{\n  \"market_facts_contract\""), out.lastIndexOf("};")+1)).markets.uk);
    expect(ukBlock).toBe(before);
  });
});

describe("AC-A6 generation failures", () => {
  it("fails on a SHA256SUMS mismatch", () => {
    const { root, dir } = scratch();
    writeFileSync(join(dir, "uk.json"), `${readFileSync(join(dir, "uk.json"), "utf8")}\n `);
    expect(() => run(root)).toThrow(/SHA256SUMS mismatch for uk\.json/);
  });
  it("fails on a duplicate fact_id", () => {
    const { root, dir } = scratch();
    editUk(dir, (uk) => uk.facts.push(JSON.parse(JSON.stringify(uk.facts[0]))));
    expect(() => run(root)).toThrow(/duplicate fact_id/);
  });
  it("fails on an unknown status", () => {
    const { root, dir } = scratch();
    editUk(dir, (uk) => { uk.facts[0].status = "maybe"; });
    expect(() => run(root)).toThrow(/schema validation/);
  });
  it("fails on an unknown gate", () => {
    const { root, dir } = scratch();
    editUk(dir, (uk) => { uk.facts[0].publish_gates = ["website-deploy", "stripe-flow1", "mystery"]; });
    expect(() => run(root)).toThrow(/unknown gate "mystery"/);
  });
  it("rejects a price fact whose publish_gates omit a mandatory gate", () => {
    const { root, dir } = scratch();
    editUk(dir, (uk) => { uk.facts[0].publish_gates = ["website-deploy"]; });
    expect(() => run(root)).toThrow(/must list mandatory gate "stripe-flow1"/);
  });
  it("rejects an attestation with no soc2-scope gate", () => {
    const { root, dir } = scratch();
    editUk(dir, (uk) => { uk.facts.find((f: any) => f.kind === "attestation").publish_gates = []; });
    expect(() => run(root)).toThrow(/mandatory gate "soc2-scope"/);
  });
  it("rejects a roadmap fact with is_capability true", () => {
    const { root, dir } = scratch();
    editUk(dir, (uk) => { uk.facts.find((f: any) => f.status === "roadmap").is_capability = true; });
    expect(() => run(root)).toThrow(/roadmap fact must have is_capability false/);
  });
  it("rejects a missing verified_on or release_evidence_version", () => {
    for (const key of ["verified_on", "release_evidence_version"]) {
      const { root, dir } = scratch();
      editUk(dir, (uk) => { delete uk.facts[2][key]; });
      expect(() => run(root)).toThrow(/schema validation/);
    }
  });
  it("rejects a release_evidence_version that disagrees with gates.json", () => {
    const { root, dir } = scratch();
    editUk(dir, (uk) => { uk.release_evidence_version = "2026-11-02.2"; uk.facts.forEach((f: any) => (f.release_evidence_version = "2026-11-02.2")); });
    expect(() => run(root)).toThrow(/release_evidence_version/);
  });
  it.each(["Our data residency is local.", "ISO 27001 aligned", "HIPAA ready", "WhatsApp-first CRM", "a sales-only tool", "sales first", "SOC 2 certified"])(
    "rejects the banned phrase %j",
    (phrase) => {
      const { root, dir } = scratch();
      editUk(dir, (uk) => { uk.facts.find((f: any) => f.fact_id === "uk.market.hub").statement = phrase; });
      expect(() => run(root)).toThrow(/banned phrase/);
    },
  );
  it("rejects extra properties (evidence boundary)", () => {
    const { root, dir } = scratch();
    editUk(dir, (uk) => { uk.facts[0].stripe_price_id = "price_123"; });
    expect(() => run(root)).toThrow(/schema validation/);
  });
});
