import { describe, expect, it } from "vitest";
import { DENY_CLAIMS } from "../../data/deny-claims.js";
import { isPrivileged } from "../access.js";
import { toolsByName, tools } from "../index.js";
import { NEEDS_BACKEND, PROBE_ARGS, SEARCH_PROBES } from "./probe-args.js";
import { scanServedSource, scanText, servedSourceFiles, stripGenerated } from "./truth-scan.js";

/**
 * Truth guard (PLAN-HELLOG-0003, AC-06). The claim is exactly this: no
 * deny-listed string in the served-content inventory (non-test source under
 * src/tools, src/data and src/prompts.ts, minus the generated catalogue block,
 * which the runtime pass covers) and none in the output of every read-only tool
 * under default arguments, the probes in probe-args.ts, and every page of the
 * paged tools. It does NOT cover untested arguments and is not a product-truth
 * gate.
 */

async function call(name: string, args: Record<string, unknown>): Promise<string | null> {
  const tool = toolsByName.get(name)!;
  const parsed = tool.schema.safeParse(args);
  if (!parsed.success) return null;
  const res = await tool.handle(parsed.data);
  return res.content.map((c) => c.text).join("\n");
}

describe("deny-list patterns", () => {
  for (const c of DENY_CLAIMS) {
    it(`${c.id}: matches its positive example (${c.kt})`, () => {
      expect(scanText(c.positive, "x", [c])).not.toHaveLength(0);
    });
    it(`${c.id}: does not match its negative example`, () => {
      expect(scanText(c.negative, "x", [c])).toHaveLength(0);
    });
  }
});

describe("truth guard: static source scan", () => {
  it("covers a sensible inventory", () => {
    expect(servedSourceFiles().length).toBeGreaterThan(40);
  });

  it("finds no deny-listed claim in served source", () => {
    const hits = scanServedSource();
    expect(hits, JSON.stringify(hits, null, 2)).toHaveLength(0);
  });

  it("fails when a deny-listed string is injected into source (the guard guards itself)", () => {
    const injected = 'const x = "HelloGrowthCRM syncs customer records with Tally";';
    expect(scanText(injected, "src/tools/injected.ts")).not.toHaveLength(0);
  });

  it("strips only the regenerated catalogue block", () => {
    const src = "a\n// >>> GENERATED BY scripts/sync-website-mirror.mjs — do not hand-edit below <<<\nTally sync\n// >>> END GENERATED <<<\nb";
    expect(stripGenerated(src)).toBe("a\nb");
  });
});

describe("truth guard: runtime output scan", () => {
  const runnable = tools.filter(
    (t) => !isPrivileged(t.definition.name) && t.definition.annotations?.readOnlyHint === true && !(t.definition.name in NEEDS_BACKEND),
  );

  it("exercises a real set of tools", () => {
    expect(runnable.length).toBeGreaterThan(30);
  });

  it("every read-only tool is either runnable offline or listed in NEEDS_BACKEND with a reason", () => {
    for (const name of Object.keys(NEEDS_BACKEND)) {
      expect(toolsByName.has(name), `NEEDS_BACKEND names an unknown tool: ${name}`).toBe(true);
    }
  });

  for (const t of runnable) {
    const name = t.definition.name;
    it(`${name}: no deny-listed claim in any probed output`, async () => {
      const argSets: Record<string, unknown>[] = [{}, ...(PROBE_ARGS[name] ?? []), ...(SEARCH_PROBES[name] ?? [])];
      let ran = 0;
      for (const args of argSets) {
        const out = await call(name, args);
        if (out === null) continue;
        ran++;
        const hits = scanText(out, `${name} ${JSON.stringify(args)}`);
        expect(hits, JSON.stringify(hits, null, 2)).toHaveLength(0);
      }
      expect(ran, `${name} rejected every probe; add arguments in probe-args.ts`).toBeGreaterThan(0);
    });
  }

  it("integrations_list: every page of the full traversal is clean", async () => {
    let offset: number | null = 0;
    let pages = 0;
    while (offset !== null && pages < 20) {
      const out = await call("integrations_list", { status: "all", limit: 200, offset });
      const body = JSON.parse(out!);
      expect(scanText(out!, `integrations_list page ${pages}`)).toHaveLength(0);
      offset = body.next_offset;
      pages++;
    }
    expect(pages).toBeGreaterThan(1);
  });

  it("fails when a deny-listed string is injected into a tool output", () => {
    const out = JSON.stringify({ a: "All India prices include GST" });
    expect(scanText(out, "injected")).not.toHaveLength(0);
  });
});
