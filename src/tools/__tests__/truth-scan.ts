/**
 * Helpers for the truth guard (PLAN-HELLOG-0003, AC-06). Kept out of the test
 * file so the guard's own tests can call them with injected strings.
 */

import { readdirSync, readFileSync, statSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { COMPETITOR_ALLOW, DENY_CLAIMS, type DenyClaim } from "../../data/deny-claims.js";

const SRC = join(dirname(fileURLToPath(import.meta.url)), "..", "..");

export interface Hit {
  id: string;
  kt: string;
  where: string;
  excerpt: string;
}

/** Remove regions the sync script regenerates; the runtime scan covers what is served from them. */
export function stripGenerated(src: string): string {
  const lines = src.split("\n");
  const out: string[] = [];
  let skipping = false;
  for (const line of lines) {
    if (line.includes(">>> GENERATED BY scripts/sync-website-mirror.mjs")) skipping = true;
    if (!skipping) out.push(line);
    if (line.includes(">>> END GENERATED <<<")) skipping = false;
  }
  return out.join("\n");
}

/** A match inside a negated sentence is a correction ("there is no TallyPrime sync"), not a claim. */
const NEGATION = /\b(?:no|not|never|without|lacks?|cannot|can't|isn't|aren't|doesn't|don't)\b/i;

function sentenceAround(text: string, index: number, length: number): string {
  const before = text.slice(0, index);
  const start = Math.max(before.lastIndexOf("."), before.lastIndexOf(";"), before.lastIndexOf("\n"), before.lastIndexOf("\\n"), before.lastIndexOf('"'));
  const rest = text.slice(index + length);
  const ends = [rest.indexOf("."), rest.indexOf(";"), rest.indexOf("\n"), rest.indexOf("\\n")].filter((i) => i >= 0);
  const end = ends.length ? Math.min(...ends) : rest.length;
  return text.slice(start + 1, index + length + end);
}

/** Remove comments: a history note in a comment is not served content. String contents are untouched. */
export function stripComments(src: string): string {
  return src
    .replace(/\/\*[\s\S]*?\*\//g, "")
    .split("\n")
    .filter((l) => !/^\s*\/\//.test(l))
    .join("\n");
}

export function scanText(text: string, where: string, claims: readonly DenyClaim[] = DENY_CLAIMS): Hit[] {
  const hits: Hit[] = [];
  for (const c of claims) {
    const re = new RegExp(c.regex.source, c.regex.flags.includes("g") ? c.regex.flags : c.regex.flags + "g");
    for (const m of text.matchAll(re)) {
      if (NEGATION.test(sentenceAround(text, m.index!, m[0].length))) continue;
      const excerpt = text.slice(Math.max(0, m.index! - 40), m.index! + m[0].length + 40).replace(/\s+/g, " ");
      if (COMPETITOR_ALLOW.some((a) => where.endsWith(a.file) && excerpt.includes(a.text))) continue;
      hits.push({ id: c.id, kt: c.kt, where, excerpt });
    }
  }
  return hits;
}

/** Files whose text is served: tools, data and prompts, minus the guard's own data files and tests. */
export function servedSourceFiles(): string[] {
  const out: string[] = [];
  const walk = (dir: string): void => {
    for (const f of readdirSync(dir)) {
      const p = join(dir, f);
      if (statSync(p).isDirectory()) {
        if (f === "__tests__") continue;
        walk(p);
      } else if (f.endsWith(".ts") && !f.endsWith(".test.ts")) {
        out.push(p);
      }
    }
  };
  walk(join(SRC, "tools"));
  walk(join(SRC, "data"));
  out.push(join(SRC, "prompts.ts"));
  const excluded = new Set(["data/deny-claims.ts", "data/claim-overrides.ts"]);
  return out.filter((p) => !excluded.has(relative(SRC, p).replace(/\\/g, "/")));
}

export function scanServedSource(): Hit[] {
  const hits: Hit[] = [];
  for (const file of servedSourceFiles()) {
    let src = readFileSync(file, "utf8").replace(/\r\n/g, "\n");
    if (file.endsWith("integrations.ts")) src = stripGenerated(src);
    src = stripComments(src);
    hits.push(...scanText(src, relative(SRC, file).replace(/\\/g, "/")));
  }
  return hits;
}
